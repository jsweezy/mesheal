void appendFloatLE(std::vector<std::uint8_t>& buf, float val) {
    std::uint8_t bytes[sizeof(float)];
    std::memcpy(bytes, &val, sizeof(float));
    buf.insert(buf.end(), bytes, bytes + sizeof(float));
}

